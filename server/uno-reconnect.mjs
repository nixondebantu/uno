import { io } from 'socket.io-client';
const URL = 'http://localhost:3999';
const wait = (s,ev)=>new Promise(r=>s.once(ev,r));
const A = io(URL,{transports:['websocket']});
await wait(A,'connect');
let tokenB=null;
A.emit('create_room',{name:'Alice',avatar:'Cat',settings:{turnTimerSeconds:null}});
const created = await wait(A,'room_created');
const code = created.roomCode;
const B = io(URL,{transports:['websocket']});
await wait(B,'connect');
B.on('player_token',p=>tokenB=p.playerToken);
B.emit('join_room',{roomCode:code,name:'Bob',avatar:'Dog'});
await wait(B,'room_joined');
A.emit('start_game',{});
await wait(A,'game_started');
const gsB = await wait(B,'game_started');
console.log('B initial hand size:', gsB.yourHand.length);
B.disconnect();
await new Promise(r=>setTimeout(r,300));
const B2 = io(URL,{transports:['websocket']});
await wait(B2,'connect');
let gotState=false, gotHand=null;
B2.on('game_state',p=>gotState=!!p.publicState);
B2.on('your_hand',p=>gotHand=p.hand.length);
B2.emit('join_room',{roomCode:code,name:'Bob',avatar:'Dog',playerToken:tokenB});
await wait(B2,'room_joined');
await new Promise(r=>setTimeout(r,200));
console.log('reconnect: room_joined OK, game_state replayed:', gotState, ', your_hand size:', gotHand);
A.close();B2.close();process.exit(0);
